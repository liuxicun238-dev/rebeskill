const fs = require('fs')
const path = require('path')

module.exports = {
  id: 'chatgpt-image-bridge.contract',
  title: 'ChatGPT image bridge remains local, authenticated and Images-compatible',
  tags: ['media', 'image', 'chatgpt', 'local-bridge'],
  paths: [
    'electron/modules/chatgpt-image-bridge.js',
    'frontend/scripts/features/chatgpt-image-bridge-settings.js'
  ],
  async run(ctx) {
    const modulePath = path.join(ctx.root, 'electron/modules/chatgpt-image-bridge.js')
    const source = fs.readFileSync(modulePath, 'utf8')
    const ipcSource = fs.readFileSync(path.join(ctx.root, 'electron/modules/ipc.js'), 'utf8')
    const preloadSource = fs.readFileSync(path.join(ctx.root, 'electron/preload.js'), 'utf8')
    const htmlSource = fs.readFileSync(path.join(ctx.root, 'frontend/index.html'), 'utf8')
    const adapterSource = fs.readFileSync(path.join(ctx.root, 'electron/modules/model-api-adapter.js'), 'utf8')

    ctx.assert.ok(source.includes("const DEFAULT_HOST = '127.0.0.1'"), 'bridge must bind to loopback only')
    ctx.assert.ok(source.includes('getSharedWebBridgeProfileDir'), 'login state must use the shared isolated external-browser profile')
    ctx.assert.ok(source.includes('chromium.connectOverCDP'), 'bridge must connect to a real external Chromium browser')
    ctx.assert.ok(source.includes('function launchNormalLoginBrowser()'), 'login must use a separate normal-browser stage')
    ctx.assert.ok(source.includes("code: 'LOGIN_BROWSER_STILL_OPEN'"), 'automation must wait until the normal login browser is closed')
    const normalArgsMatch = source.match(/function buildNormalLoginArgs\(profileDir\) \{[\s\S]*?\n\}/)
    ctx.assert.ok(normalArgsMatch, 'normal login browser arguments must remain explicit and auditable')
    ctx.assert.ok(!normalArgsMatch[0].includes('remote-debugging'), 'normal login browser must not use remote debugging')
    ctx.assert.ok(!normalArgsMatch[0].includes('enable-automation'), 'normal login browser must not use automation flags')
    ctx.assert.ok(source.includes("readRegistryAppPath('chrome.exe')"), 'Windows Chrome must be discovered through App Paths')
    ctx.assert.ok(!/\{ app,\s*BrowserWindow/.test(source), 'bridge must not create an Electron BrowserWindow')
    ctx.assert.ok(!source.includes('session.fromPartition'), 'bridge must not use an Electron web session')
    ctx.assert.ok(source.includes("pathname === '/v1/images/generations'"), 'bridge must expose the OpenAI-compatible image endpoint')
    ctx.assert.ok(source.includes("pathname === '/v1/chat/completions'"), 'bridge must expose the OpenAI-compatible chat endpoint')
    ctx.assert.ok(source.includes("modelId: 'chatgpt-web-chat'"), 'bridge must provide a separate webpage chat model')
    ctx.assert.ok(source.includes('vision: true'), 'webpage chat must declare vision so Lingxi forwards uploaded images')
    ctx.assert.ok(source.includes('function attachComposerImages('), 'webpage chat must attach images into the ChatGPT composer')
    ctx.assert.ok(!source.includes('暂不支持转发图片'), 'webpage chat must no longer drop image parts')
    ctx.assert.ok(source.includes('function buildWebChatPrompt('), 'web chat must translate Lingxi history into the webpage prompt')
    ctx.assert.ok(source.includes('function waitForAssistantReply('), 'web chat must wait for the actual webpage assistant response')
    ctx.assert.ok(source.includes('const chatSessions = new Map()'), 'Lingxi sessions must map to isolated ChatGPT pages')
    ctx.assert.ok(source.includes('function getContinuationMessages('), 'continuous Lingxi turns must reuse the same ChatGPT conversation')
    ctx.assert.ok(source.includes("plan.promptMode === 'resync'"), 'compressed Lingxi history must resync inside the existing ChatGPT conversation')
    ctx.assert.ok(source.includes('session.conversationUrl'), 'each Lingxi task must remain pinned to its mapped ChatGPT conversation URL')
    ctx.assert.ok(source.includes('function parseLingxiToolCalls('), 'web tool requests must pass through a strict parser')
    ctx.assert.ok(source.includes('INVALID_TOOL_CALL_PROTOCOL'), 'invalid or unauthorized web tool output must be rejected')
    ctx.assert.ok(source.includes('MAX_CHAT_SESSION_PAGES'), 'web chat pages must have a bounded LRU-style limit')
    ctx.assert.ok(source.includes('crypto.timingSafeEqual'), 'local mutating endpoints must require the saved bridge key')
    ctx.assert.ok(source.includes('queueTail'), 'web generations must be serialized')
    ctx.assert.ok(!source.includes('document.cookie'), 'bridge must not scrape webpage cookies')
    ctx.assert.ok(!source.includes('accessToken'), 'bridge must not extract ChatGPT access tokens')
    ctx.assert.ok(!source.includes('bridgeContext.request.get'), 'image bytes must use the signed-in browser network stack, not a separate HTTP client')
    ctx.assert.ok(source.includes('function sanitizeErrorMessage('), 'upstream failures must be sanitized before reaching the renderer')
    ctx.assert.ok(source.includes("cookie|authorization"), 'sensitive request headers must be redacted from errors')
    ctx.assert.ok(source.includes("code: 'IMAGE_READ_FAILED'"), 'image-read failures must use a safe stable error')
    ctx.assert.ok(ipcSource.includes('chatGptImageBridge.registerIPC'), 'bridge IPC must be registered at application startup')
    ctx.assert.ok(preloadSource.includes('getChatGptImageBridgeSuggestedModel'), 'renderer must receive a narrow bridge API')
    ctx.assert.ok(preloadSource.includes('getChatGptWebBridgeSuggestedChatModel'), 'renderer must be able to add the webpage chat model')
    ctx.assert.ok(htmlSource.includes('chatgptImageBridgeAddBtn'), 'settings must expose one-click model setup')
    ctx.assert.ok(htmlSource.includes('chatgptWebBridgeAddChatBtn'), 'settings must expose the separate webpage chat model')
    ctx.assert.ok(htmlSource.includes('chatgptWebBridgePageModel'), 'ChatGPT webpage model picker must sit next to add-chat')
    ctx.assert.ok(htmlSource.includes('chatgptWebBridgeThinkingLevel'), 'ChatGPT thinking level must sit next to add-chat')
    ctx.assert.ok(htmlSource.includes('推理强度'), 'ChatGPT prefs must use the webpage reasoning-strength control')
    ctx.assert.ok(htmlSource.includes('web-bridge-picker-menu'), 'webpage prefs must use a custom overlay menu, not a native select')
    ctx.assert.ok(!/<select[^>]*id="chatgptWebBridgePageModel"/.test(htmlSource), 'ChatGPT model picker must not be a native select')
    ctx.assert.ok(source.includes('applyChatGptPageModel'), 'ChatGPT must apply the selected page model before sending')
    ctx.assert.ok(preloadSource.includes('chatgpt-image-bridge:set-page-prefs'))
    ctx.assert.ok(htmlSource.includes('chatgpt-image-bridge-settings.js'), 'bridge settings behavior must be loaded')
    ctx.assert.ok(adapterSource.includes("headers['x-lingxi-session-id']"), 'model requests must carry a stable hashed Lingxi session id')
    ctx.assert.ok(!adapterSource.includes("=== 'chatgpt-web-bridge') return []"), 'webpage chat must still receive Lingxi tool schemas, not an empty list')
    ctx.assert.ok(adapterSource.includes('filterWebGptCoreTools'), 'webpage chat must shrink the pasted tool list to core search/read/edit/shell tools')
    ctx.assert.ok(source.includes('getWebGptCoreTools'), 'webpage prompt must reject tools outside the web-GPT core allowlist')

    const promptMatch = source.match(/function buildPrompt\(body = \{\}\) \{[\s\S]*?\n\}/)
    ctx.assert.ok(promptMatch, 'prompt normalizer must remain present')
    ctx.assert.ok(source.includes('一次只支持生成 1 张图片'), 'webpage image generation currently supports n=1')
    ctx.assert.ok(!source.includes('composeChatGptWebImagePrompt'), 'webpage image prompts must not be stuffed into one composer message')
    const dataUrlMatch = source.match(/function parseDataUrl\(dataUrl\) \{[\s\S]*?\n\}/)
    ctx.assert.ok(dataUrlMatch, 'data URL decoder must remain present')
  }
}
